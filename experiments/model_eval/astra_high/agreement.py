"""Astra round vs Fable round: how far the two evaluator models agree.

    python3 agreement.py        (writes agreement.md beside this script)

Both rounds rated the same 150 simulations with the same packets, labels and rubric; each round
has three evaluators whose ratings combine into a majority vote per (model, object, category)
exactly as combine.py does.  Per category this reports
  - the exact-match rate of the two rounds' majority votes over the 150 simulations (and over the
    simulations both rounds graded, i.e. neither vote n/a), the rate within one step
    (High-Moderate or Moderate-Low counts as within one), and the confusion table;
  - per coding-agent model, the High/Moderate/Low counts of each round side by side;
  - for context, each round's own unanimity (all three of its evaluators gave the same rating)."""
import json, sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from build_packets import MAPPINGS, MODELS, categories          # noqa: E402
from combine import CATS, ORDER, vote                            # noqa: E402

ROUNDS = {"Fable": HERE.parent, "Astra": HERE}
NAMES = {"geometry": "Geometry", "bc": "BC", "material": "Material"}
LEVELS = ("High", "Moderate", "Low", "n/a")


def load(folder):
    """(model, object) -> {category: [rating of evaluator 1, 2, 3]}"""
    out = {}
    for k in (1, 2, 3):
        inv = {lab: m for m, lab in json.load(open(MAPPINGS / f"mapping_{k}.json")).items()}
        for e in json.load(open(folder / f"eval_{k}.json")):
            d = out.setdefault((inv[e["label"]], e["object"]), {c: [None] * 3 for c in CATS})
            for c in CATS:
                d[c][k - 1] = e.get(c)
    return out


def main():
    objs = [o for _, os_ in categories() for o in os_]
    models = list(MODELS)
    keys = [(m, o) for m in models for o in objs]
    data = {r: load(f) for r, f in ROUNDS.items()}
    votes = {r: {(key, c): vote(data[r][key][c])[0] for key in keys for c in CATS} for r in ROUNDS}
    md = ["# Astra (GPT-6-Astra, high effort) vs Fable (claude-fable-5-1, high effort)", "",
          "Same 150 simulations, packets, blinded labels and rubric; three evaluators per round, "
          "combined by majority vote as in `combine.py`. Generated by `agreement.py`.", ""]
    md += ["## Majority votes: agreement per category", "",
           "| Category | Exact match (all 150) | Exact match (both graded) | Within one step | "
           "Fable higher | Astra higher |", "|---|---|---|---|---|---|"]
    conf = {}
    for c in CATS:
        pairs = [(votes["Fable"][(k, c)], votes["Astra"][(k, c)]) for k in keys]
        conf[c] = Counter(pairs)
        same = sum(f == a for f, a in pairs)
        graded = [(f, a) for f, a in pairs if f in ORDER and a in ORDER]
        gs = sum(f == a for f, a in graded)
        within = sum(abs(ORDER[f] - ORDER[a]) <= 1 for f, a in graded)
        fh = sum(ORDER[f] > ORDER[a] for f, a in graded)
        ah = sum(ORDER[a] > ORDER[f] for f, a in graded)
        md.append(f"| {NAMES[c]} | {same}/{len(pairs)} ({100 * same / len(pairs):.0f} %) | "
                  f"{gs}/{len(graded)} ({100 * gs / len(graded):.0f} %) | "
                  f"{within}/{len(graded)} ({100 * within / len(graded):.0f} %) | {fh} | {ah} |")
    md += ["", "## High/Moderate/Low counts per coding-agent model (majority votes)", "",
           "| Model | Category | Fable H/M/L | Astra H/M/L |", "|---|---|---|---|"]

    def hml(r, m, c):
        t = Counter(votes[r][((m, o), c)] for o in objs)
        s = f"{t['High']}/{t['Moderate']}/{t['Low']}"
        return s + (f" (+{t['n/a']} n/a)" if t["n/a"] else "")
    for m in models:
        for c in CATS:
            md.append(f"| {m.capitalize()} | {NAMES[c]} | {hml('Fable', m, c)} | {hml('Astra', m, c)} |")
    md += ["", "## Confusion of majority votes (rows Fable, columns Astra)", ""]
    for c in CATS:
        md += [f"**{NAMES[c]}**", "", "| Fable \\ Astra | " + " | ".join(LEVELS) + " |",
               "|---|" + "---|" * len(LEVELS)]
        for f in LEVELS:
            md.append(f"| {f} | " + " | ".join(str(conf[c][(f, a)]) for a in LEVELS) + " |")
        md.append("")
    md += ["## Within-round unanimity (all three evaluators gave the same rating)", "",
           "| Category | Fable | Astra |", "|---|---|---|"]
    for c in CATS:
        row = []
        for r in ROUNDS:
            u = sum(len(set(data[r][k][c])) == 1 for k in keys)
            row.append(f"{u}/{len(keys)} ({100 * u / len(keys):.0f} %)")
        md.append(f"| {NAMES[c]} | " + " | ".join(row) + " |")
    # Where the rounds differ: criterion scores summed over all 450 ratings of a round
    # (3 evaluators x 150), partial / failed.
    md += ["", "## Criterion scores, all 450 ratings per round (partial / failed)", "",
           "| Criterion | Fable | Astra |", "|---|---|---|"]
    cnt = {r: {} for r in ROUNDS}
    for r, folder in ROUNDS.items():
        for k in (1, 2, 3):
            for e in json.load(open(folder / f"eval_{k}.json")):
                for i, s in e.get("criteria", {}).items():
                    cnt[r].setdefault(i, Counter())[s] += 1
    for i in ("G1", "G2", "G3", "G4", "B1", "B2", "B3", "B4", "M1", "M2", "M3"):
        md.append(f"| {i} | " + " | ".join(
            f"{cnt[r].get(i, Counter())['partial']} / {cnt[r].get(i, Counter())['failed']}"
            for r in ROUNDS) + " |")
    (HERE / "agreement.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
