"""Astra vs Fable: how far the two evaluator families agree.

    python3 scripts/agreement.py          (writes results/agreement.md)

Both families rated the same simulations with the same packets, labels and rubric; each family
has three evaluators whose ratings combine into a majority vote per (model, object, category)
exactly as combine.py does.  The first family of the config (Fable) is the reference, the rows
of the confusion table.  Per category this reports
  - the exact-match rate of the two families' majority votes over all simulations (and over the
    simulations both graded, i.e. neither vote n/a), the rate within one step
    (High-Moderate or Moderate-Low counts as within one), and the confusion table;
  - per coding-agent model, the High/Moderate/Low counts of each family side by side;
  - for context, each family's own unanimity (all three of its evaluators gave the same rating)."""
import argparse, json
from collections import Counter

from combine import CATS, ORDER, vote
from config import NUMBER_WORDS, Grading

NAMES = {"geometry": "Geometry", "bc": "BC", "material": "Material"}
LEVELS = ("High", "Moderate", "Low", "n/a")


def load(folder, mappings, n):
    """(model, object) -> {category: [rating of evaluator 1, ..., n]}, from folder/eval_<k>.json
    and the label mappings mappings/mapping_<k>.json.  drift.py reads the paper's records with it
    too, under the paper's own mappings."""
    out = {}
    for k in range(1, n + 1):
        inv = {lab: m for m, lab in json.load(open(mappings / f"mapping_{k}.json")).items()}
        for e in json.load(open(folder / f"eval_{k}.json")):
            d = out.setdefault((inv[e["label"]], e["object"]), {c: [None] * n for c in CATS})
            for c in CATS:
                d[c][k - 1] = e.get(c)
    return out


def main():
    argparse.ArgumentParser(description=__doc__.split("\n\n")[0]).parse_args()
    g = Grading()
    fams = list(g.families)[:2]
    FAMS = {g.family(f).get("display", f.capitalize()): g.family_dir(f) for f in fams}
    R0, R1 = FAMS                                                 # reference, compared
    t0, t1 = (g.family(f)["title"] for f in fams)
    objs = [o for _, os_ in g.categories() for o in os_]
    models = g.models
    keys = [(m, o) for m in models for o in objs]
    N, E = len(keys), g.evaluators
    data = {r: load(f, g.mappings, E) for r, f in FAMS.items()}
    votes = {r: {(key, c): vote(data[r][key][c])[0] for key in keys for c in CATS} for r in FAMS}
    md = [f"# {R1} ({t1}) vs {R0} ({t0})", "",
          f"Same {N} simulations, packets, blinded labels and rubric; {NUMBER_WORDS[E].lower()} "
          "evaluators per family, combined by majority vote as in `combine.py`. Generated by `agreement.py`.", ""]
    md += ["## Majority votes: agreement per category", "",
           f"| Category | Exact match (all {N}) | Exact match (both graded) | Within one step | "
           f"{R0} higher | {R1} higher |", "|---|---|---|---|---|---|"]
    conf = {}
    for c in CATS:
        pairs = [(votes[R0][(k, c)], votes[R1][(k, c)]) for k in keys]
        conf[c] = Counter(pairs)
        same = sum(f == a for f, a in pairs)
        graded = [(f, a) for f, a in pairs if f in ORDER and a in ORDER]
        gs = sum(f == a for f, a in graded)
        within = sum(abs(ORDER[f] - ORDER[a]) <= 1 for f, a in graded)
        fh = sum(ORDER[f] > ORDER[a] for f, a in graded)
        ah = sum(ORDER[a] > ORDER[f] for f, a in graded)
        md.append(f"| {NAMES[c]} | {same}/{len(pairs)} ({100 * same / len(pairs):.0f} %) | "
                  f"{gs}/{len(graded)} ({100 * gs / len(graded):.0f} %) | "
                  f"{within}/{len(graded)} ({100 * within / len(graded):.0f} %) | {fh} | {ah} |")
    md += ["", "## High/Moderate/Low counts per coding-agent model (majority votes)", "",
           f"| Model | Category | {R0} H/M/L | {R1} H/M/L |", "|---|---|---|---|"]

    def hml(r, m, c):
        t = Counter(votes[r][((m, o), c)] for o in objs)
        s = f"{t['High']}/{t['Moderate']}/{t['Low']}"
        return s + (f" (+{t['n/a']} n/a)" if t["n/a"] else "")
    for m in models:
        for c in CATS:
            md.append(f"| {g.display(m)} | {NAMES[c]} | {hml(R0, m, c)} | {hml(R1, m, c)} |")
    md += ["", f"## Confusion of majority votes (rows {R0}, columns {R1})", ""]
    for c in CATS:
        md += [f"**{NAMES[c]}**", "", f"| {R0} \\ {R1} | " + " | ".join(LEVELS) + " |",
               "|---|" + "---|" * len(LEVELS)]
        for f in LEVELS:
            md.append(f"| {f} | " + " | ".join(str(conf[c][(f, a)]) for a in LEVELS) + " |")
        md.append("")
    md += [f"## Within-family unanimity (all {NUMBER_WORDS[E].lower()} evaluators gave the same rating)", "",
           f"| Category | {R0} | {R1} |", "|---|---|---|"]
    for c in CATS:
        row = []
        for r in FAMS:
            u = sum(len(set(data[r][k][c])) == 1 for k in keys)
            row.append(f"{u}/{len(keys)} ({100 * u / len(keys):.0f} %)")
        md.append(f"| {NAMES[c]} | " + " | ".join(row) + " |")
    # Where the families differ: criterion scores summed over all ratings of a family
    # (evaluators x simulations), partial / failed.
    md += ["", f"## Criterion scores, all {E * N} ratings per family (partial / failed)", "",
           f"| Criterion | {R0} | {R1} |", "|---|---|---|"]
    cnt = {r: {} for r in FAMS}
    for r, folder in FAMS.items():
        for k in range(1, E + 1):
            for e in json.load(open(folder / f"eval_{k}.json")):
                for i, s in e.get("criteria", {}).items():
                    cnt[r].setdefault(i, Counter())[s] += 1
    for i in ("G1", "G2", "G3", "G4", "B1", "B2", "B3", "B4", "M1", "M2", "M3"):
        md.append(f"| {i} | " + " | ".join(
            f"{cnt[r].get(i, Counter())['partial']} / {cnt[r].get(i, Counter())['failed']}"
            for r in FAMS) + " |")
    (g.results / "agreement.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
