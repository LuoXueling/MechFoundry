"""Drift from the paper's grading, measured on the three Claude batches both gradings rated.

    python3 scripts/drift.py          (writes results/drift.md)

Haiku, Sonnet and Opus are graded here on the batch roots the paper graded (the same runs and
the exact category figures its evaluators saw), so any change in their ratings comes from the
grading, not the runs.  For each such model (matched by batch root), per evaluator family (Fable,
Astra) and per category, this compares its majority votes (combine.vote, as combine.py and
agreement.py use) object by object with the paper's: exact match, within one step, how often
each grading is the higher, and the High/Moderate/Low counts of each.  A positive mean shift means
this grading rates the model higher.

The paper's ratings are read from records/paper/ under the paper's own label mappings and model
keys (records/paper/round.json); this is the only script that reads the records.

What it cannot separate: the paper's packets held three agents, these hold six, so an
evaluator's calibration against its neighbours is part of what is measured."""
import argparse, json
from collections import Counter

from agreement import NAMES, load
from combine import CATS, ORDER, vote
from config import EVAL, Grading

PAPER = EVAL / "records" / "paper"
# Where the paper's committed ratings of each family are (its Fable round at the folder's top
# level, its Astra round in astra_high/, as they were committed).
PAPER_RATINGS = {"fable": PAPER, "astra": PAPER / "astra_high"}


def main():
    argparse.ArgumentParser(description=__doc__.split("\n\n")[0]).parse_args()
    g = Grading()
    ref = json.load(open(PAPER / "round.json"))
    by_root = {m["root"]: m["key"] for m in ref["models"]}
    pairs = [(m, by_root[g.root(m)]) for m in g.models if g.root(m) in by_root]
    objs = [o for _, os_ in g.categories() for o in os_]
    fams = [f for f in g.families if f in PAPER_RATINGS]
    names = ", ".join(g.display(m) for m, _ in pairs)
    md = ["# Drift of the Claude batches: this grading vs the paper's", "",
          f"{names}: the same {len(objs)} runs each, graded in both; majority votes of "
          f"{g.evaluators} evaluators per family. Generated by `scripts/drift.py`. Positive mean "
          f"shift: this grading rates higher (High 2, Moderate 1, Low 0; n/a left out).", ""]
    for f in fams:
        # A family that has not graded yet (one family can run days before the other, e.g. when
        # one login's usage limit holds it back) is named as pending, not a traceback.
        missing = [k for k in range(1, g.evaluators + 1)
                   if not (g.family_dir(f) / f"eval_{k}.json").exists()]
        if missing:
            md += [f"## {g.family(f).get('display', f)}", "",
                   f"Not graded yet: no `eval_{missing[0]}.json` in `{g.family_dir(f)}`.", ""]
            continue
        new = load(g.family_dir(f), g.mappings, g.evaluators)
        old = load(PAPER_RATINGS[f], PAPER / "mappings", int(ref["evaluators"]))
        md += [f"## {g.family(f).get('display', f)}", "",
               "| Model | Category | Exact match | Within one step | Now higher | Paper higher "
               "| Mean shift | Paper H/M/L | Now H/M/L |", "|---|---|---|---|---|---|---|---|---|"]
        for m, mref in pairs:
            for c in CATS:
                vn = [vote(new[(m, o)][c])[0] for o in objs]
                vo = [vote(old[(mref, o)][c])[0] for o in objs]
                both = [(x, y) for x, y in zip(vn, vo) if x in ORDER and y in ORDER]
                ex = sum(x == y for x, y in zip(vn, vo))
                w1 = sum(abs(ORDER[x] - ORDER[y]) <= 1 for x, y in both)
                hi = sum(ORDER[x] > ORDER[y] for x, y in both)
                lo = sum(ORDER[x] < ORDER[y] for x, y in both)
                shift = sum(ORDER[x] - ORDER[y] for x, y in both) / len(both) if both else float("nan")
                tn, to = Counter(vn), Counter(vo)
                md.append(f"| {g.display(m)} | {NAMES[c]} | {ex}/{len(objs)} | {w1}/{len(both)} | {hi} | "
                          f"{lo} | {shift:+.2f} | {to['High']}/{to['Moderate']}/{to['Low']} | "
                          f"{tn['High']}/{tn['Moderate']}/{tn['Low']} |")
        md.append("")
    out = g.results / "drift.md"
    out.write_text("\n".join(md))
    print("\n".join(md))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
